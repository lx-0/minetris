// ── State ─────────────────────────────────────────────────────────────────────
let _lang = 'en';

// ── Public API ────────────────────────────────────────────────────────────────

/** Detect browser language, load saved preference, set _lang. Call before initSettings(). */
function initI18n() {
  let saved;
  try { saved = localStorage.getItem(I18N_LANG_KEY); } catch (_) {}
  if (saved && SUPPORTED_LANGS.indexOf(saved) !== -1) {
    _lang = saved;
  } else {
    const nav = (navigator.language || 'en').toLowerCase();
    const code = nav.slice(0, 2);
    _lang = SUPPORTED_LANGS.indexOf(code) !== -1 ? code : 'en';
  }
  document.documentElement.lang = _lang;
}

/** Returns the current language code (e.g. 'en', 'ja'). */
function getLanguage() {
  return _lang;
}

/** Switch to a new language, persist, and re-apply all DOM translations. */
function setLanguage(code) {
  if (SUPPORTED_LANGS.indexOf(code) === -1) code = 'en';
  _lang = code;
  try { localStorage.setItem(I18N_LANG_KEY, code); } catch (_) {}
  document.documentElement.lang = code;
  applyTranslations();
}

/**
 * Look up a translation string for the current language.
 * Falls back to English, then returns the raw key if not found.
 */
function t(key) {
  const dict = TRANSLATIONS[_lang];
  if (dict && dict[key] !== undefined) return dict[key];
  const en = TRANSLATIONS.en;
  if (en && en[key] !== undefined) return en[key];
  return key;
}

/**
 * Apply translations to all [data-i18n] elements in the DOM.
 * Also updates language picker button states.
 */
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    // Only update if different to avoid unnecessary reflows
    if (el.textContent !== val) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(function(el) {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  // Update language picker button active state
  SUPPORTED_LANGS.forEach(function(code) {
    var btn = document.getElementById('lang-btn-' + code);
    if (btn) btn.classList.toggle('lang-btn-active', code === _lang);
  });
}

// ── Number & Date helpers ─────────────────────────────────────────────────────

/** Format a number with locale-appropriate thousands separators. */
function fmtLocalNumber(n) {
  try {
    return n.toLocaleString(LANG_LOCALE[_lang] || _lang);
  } catch (_) {
    return n.toLocaleString();
  }
}

/**
 * Format a "YYYY-MM-DD" date string into a locale-appropriate short date.
 * e.g. "2024-03-15" → "Mar 15" (en), "15 mars" (fr), "3月15日" (ja)
 */
function fmtLocalDate(dateStr) {
  try {
    const parts = dateStr.split('-');
    const date = new Date(Date.UTC(+parts[0], +parts[1] - 1, +parts[2]));
    return date.toLocaleDateString(LANG_LOCALE[_lang] || _lang, { month: 'short', day: 'numeric' });
  } catch (_) {
    // Fallback: original English format
    const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
    const p = dateStr.split('-');
    return MONTHS[parseInt(p[1], 10) - 1] + ' ' + parseInt(p[2], 10);
  }
}
